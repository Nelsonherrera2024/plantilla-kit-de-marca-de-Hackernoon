// Compiles every SVG in src/icons/ into src/components/ui/svgIcons.js.
// Usage: drop/replace an .svg in src/icons, then run `npm run icons`.
// Icons are expected to be single-colour (fill is replaced by currentColor).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, basename } from 'node:path';

const SRC = new URL('../src/icons/', import.meta.url).pathname;
const OUT = new URL('../src/components/ui/svgIcons.js', import.meta.url).pathname;

const polyToPath = (pts) => {
  const n = pts.trim().split(/[\s,]+/).map(Number);
  let d = '';
  for (let i = 0; i < n.length; i += 2) d += `${i ? 'L' : 'M'}${n[i]} ${n[i + 1]}`;
  return d + 'Z';
};

const icons = {};
for (const file of readdirSync(SRC).filter((f) => f.endsWith('.svg')).sort()) {
  const svg = readFileSync(join(SRC, file), 'utf8');
  const viewBox = (svg.match(/viewBox="([^"]+)"/) || [, '0 0 24 24'])[1];
  const paths = [];
  for (const m of svg.matchAll(/<(path|polygon|rect)\b([^>]*)\/?>/g)) {
    const [, tag, attrs] = m;
    const a = (k) => (attrs.match(new RegExp(`\\b${k}="([^"]+)"`)) || [])[1];
    // A path's leading relative 'm' is absolute in its own element; make it explicit
    // so subpaths stay put once every shape is merged into a single <path>.
    if (tag === 'path') paths.push(a('d').trim().replace(/^m/, 'M'));
    else if (tag === 'polygon') paths.push(polyToPath(a('points')));
    else if (tag === 'rect') {
      const [x, y, w, h] = ['x', 'y', 'width', 'height'].map((k) => +(a(k) || 0));
      paths.push(`M${x} ${y}h${w}v${h}h${-w}Z`);
    }
  }
  icons[basename(file, '.svg')] = { viewBox, d: paths.join('') };
}

writeFileSync(
  OUT,
  `// AUTO-GENERATED by scripts/build-icons.mjs from src/icons/*.svg — do not edit by hand.\n` +
    `export const SVG_ICONS = ${JSON.stringify(icons, null, 2)};\n`,
);
console.log(`Built ${Object.keys(icons).length} icons → src/components/ui/svgIcons.js`);
