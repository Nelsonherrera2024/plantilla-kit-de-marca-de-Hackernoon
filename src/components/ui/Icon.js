const cache = {};
function compile(name) {
  if (cache[name]) return cache[name];
  const rows = GLYPHS[name] || GLYPHS.home;
  let d = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === '#') {
        let len = 1;
        while (row[x + len] === '#') len++;
        d += `M${x} ${y}h${len}v1h-${len}z`;
        x += len;
      } else x++;
    }
  });
  cache[name] = d;
  return d;
}

// Optional SVG icon set: drop SVGs into src/icons/ and run `npm run icons`.
// Then map the semantic names used across the site onto those files here, e.g.
//   home: 'my-home-icon',
// Names without an alias fall back to the built-in 12×12 pixel glyphs above.
export const ALIASES = {};

const resolve = (name) => SVG_ICONS[ALIASES[name] || name];

/** Brand SVG icons first, then the remaining 12×12 pixel UI glyphs. */
export const iconNames = [
  ...Object.keys(SVG_ICONS),
  ...Object.keys(GLYPHS).filter((n) => !ALIASES[n]),
];
export const glyph = (name) => GLYPHS[name];

export default function Icon({ name, size = 24, className, title, ...rest }) {
  const svg = resolve(name);
  return (
    <svg
      viewBox={svg ? svg.viewBox : '0 0 12 12'}
      width={size}
      height={size}
      className={className}
      shapeRendering="crispEdges"
      fill="currentColor"
      aria-hidden={title ? undefined : true}
      role={title ? 'img' : undefined}
      focusable="false"
      {...rest}
    >
      {title && <title>{title}</title>}
      <path d={svg ? svg.d : compile(name)} />
    </svg>
  );
}
